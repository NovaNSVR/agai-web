for (const [lang, keys] of Object.entries(translations)) {
  const filePath = join(localesDir, `${lang}.json`);
  const raw = readFileSync(filePath, "utf8").replace(/^﻿/, "");
  const data = JSON.parse(raw);

  if (!data.forCreators) {
    console.error(`No forCreators section in ${lang}.json`);
    continue;
  }

  Object.assign(data.forCreators, keys);
  writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`✓ ${lang}.json — added ${Object.keys(keys).length} keys`);
}
